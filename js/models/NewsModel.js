export class NewsModel {
    static STORAGE_KEY = 'massa_news_v3';

    static cleanLegacyData() {
        try {
            localStorage.removeItem('biougra_news');
            localStorage.removeItem('agadir_news');
            localStorage.removeItem('massa_news_v2');
        } catch (e) {}
    }

    static init() {
        this.cleanLegacyData();
        if (!localStorage.getItem(this.STORAGE_KEY)) {
            localStorage.setItem(this.STORAGE_KEY, JSON.stringify(defaultNews));
        }
    }

    static getAll() {
        this.init();
        try {
            const list = JSON.parse(localStorage.getItem(this.STORAGE_KEY));
            if (Array.isArray(list) && list.length > 0) return list;
            this.saveAll(defaultNews);
            return defaultNews;
        } catch (e) {
            return defaultNews;
        }
    }

    static getById(id) {
        const news = this.getAll();
        return news.find(item => item.id === Number(id) || item.id === id);
    }

    static saveAll(newsArray) {
        localStorage.setItem(this.STORAGE_KEY, JSON.stringify(newsArray));
    }

    static add(item) {
        const news = this.getAll();
        item.id = Date.now();
        news.unshift(item);
        this.saveAll(news);
        return item;
    }

    static update(id, updatedData) {
        let news = this.getAll();
        news = news.map(item => item.id === Number(id) || item.id === id ? { ...item, ...updatedData } : item);
        this.saveAll(news);
    }

    static delete(id) {
        let news = this.getAll();
        news = news.filter(item => item.id !== Number(id) && item.id !== id);
        this.saveAll(news);
    }
}
